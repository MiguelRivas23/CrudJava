-- ============================================================
-- Base de datos crud_db en Oracle
-- En Oracle una "base de datos" para una aplicación es un esquema = un usuario.
-- ============================================================

-- PASO 1: conéctate como SYSTEM (o SYS) al servicio XEPDB1 y ejecuta:
CREATE USER crud_db IDENTIFIED BY "crud_db"
    DEFAULT TABLESPACE users
    QUOTA UNLIMITED ON users;

GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW TO crud_db;

-- PASO 2: conéctate ahora como crud_db / crud_db y ejecuta lo siguiente.
-- (Opcional: si no lo haces, el backend crea estas tablas solo al arrancar.)

CREATE TABLE departamento (
    id      NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR2(255) NOT NULL
);

-- Un departamento tiene uno o más municipios (relación 1 a N)
CREATE TABLE municipio (
    id               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR2(255) NOT NULL,
    departamento_id  NUMBER(19) NOT NULL,
    CONSTRAINT fk_municipio_departamento
        FOREIGN KEY (departamento_id) REFERENCES departamento (id)
);

CREATE TABLE usuarios (
    id        NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username  VARCHAR2(255) NOT NULL UNIQUE,
    password  VARCHAR2(255) NOT NULL   -- hash BCrypt
);

